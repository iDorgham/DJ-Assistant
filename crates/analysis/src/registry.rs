//! Model specification and registry definitions.

use serde::{Deserialize, Serialize};

/// Specification for an ONNX analysis model.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ModelSpec {
    /// Identifier (e.g. "smoke_test", "beat_grid", "key_detector").
    pub id: String,
    /// Semantic version of the model asset (e.g. "1.0.0").
    pub version: String,
    /// Relative filename or path (e.g. "smoke_test.onnx").
    pub filename: String,
    /// Expected SHA-256 digest of the model file.
    pub sha256: String,
    /// Expected audio input sample rate (Hz).
    pub sample_rate: u32,
    /// Expected channel count (e.g. 1 for mono).
    pub channels: usize,
}

impl ModelSpec {
    /// Creates the standard smoke-test model specification.
    ///
    /// The asset is a 61-byte `y = Relu(x)` graph checked into
    /// `fixtures/models/smoke_test.onnx` and regenerated by
    /// `scripts/make-smoke-model.py`. `Relu` (rather than `Identity`) is used so the
    /// graph also loads on the operator-trimmed ONNX Runtime bundled with Edge
    /// WebView2; the smoke test feeds a positive input, for which `Relu(x) == x`.
    /// The digest below is pinned by `smoke_test_fixture_matches_spec` so the file and
    /// this spec cannot drift apart.
    pub fn smoke_test() -> Self {
        Self {
            id: "smoke_test".to_string(),
            version: "1.0.0".to_string(),
            filename: "smoke_test.onnx".to_string(),
            sha256: "5bd717dd17f1a40364178ea8aff2017dabc1221b13b681cd8d1a6809af1b5196".to_string(),
            sample_rate: 44100,
            channels: 1,
        }
    }

    /// Absolute path to this model's checked-in fixture asset.
    ///
    /// Production code resolves models from a configurable models directory; this
    /// helper exists so tests can locate and verify the committed fixture.
    pub fn fixture_path(&self) -> std::path::PathBuf {
        std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(|p| p.parent())
            .expect("crate lives at <repo>/crates/analysis")
            .join("fixtures")
            .join("models")
            .join(&self.filename)
    }
}

/// A registry containing one or more model specifications.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq, Eq)]
pub struct ModelRegistry {
    pub models: Vec<ModelSpec>,
}

impl ModelRegistry {
    /// Loads registry from a JSON string.
    pub fn from_json(json_str: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(json_str)
    }

    /// Serializes registry to a pretty JSON string.
    pub fn to_json(&self) -> Result<String, serde_json::Error> {
        serde_json::to_string_pretty(self)
    }

    /// Finds a model spec by its identifier.
    pub fn find(&self, id: &str) -> Option<&ModelSpec> {
        self.models.iter().find(|m| m.id == id)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn smoke_test_spec_serializes_and_deserializes() {
        let registry = ModelRegistry {
            models: vec![ModelSpec::smoke_test()],
        };

        let json = registry.to_json().expect("Should serialize");
        let parsed = ModelRegistry::from_json(&json).expect("Should deserialize");
        assert_eq!(registry, parsed);

        let smoke = parsed.find("smoke_test").expect("Should find smoke test");
        assert_eq!(smoke.id, "smoke_test");
        assert_eq!(smoke.version, "1.0.0");
    }

    /// Guards the checked-in ONNX asset against the digest declared in [`ModelSpec`].
    ///
    /// This runs without the ONNX Runtime installed, so CI still verifies model integrity
    /// even when it cannot execute inference.
    #[test]
    fn smoke_test_fixture_matches_spec() {
        let spec = ModelSpec::smoke_test();
        let path = spec.fixture_path();

        assert!(path.exists(), "missing fixture: {}", path.display());

        let bytes = std::fs::read(&path).expect("Should read smoke test fixture");
        let actual = crate::checksum::compute_sha256(&bytes);

        assert_eq!(
            actual,
            spec.sha256,
            "{} drifted from ModelSpec::smoke_test(); \
             re-run scripts/make-smoke-model.py and update the spec digest",
            path.display()
        );
    }
}
