// Regenerates the skill manifest and the human routing doc from what is
// actually installed, plus `skills.policy.json`.
//
//   node scripts/skills/inventory.mjs
//
// Outputs:
//   .opencode/skill-manifest.json   machine index used by the matcher / subagents
//   docs/context/SKILL_ROUTING.md   grouped priority tables for humans

import fs from "node:fs";
import {
  ROUTING_DOC,
  MANIFEST_PATH,
  estimateTokens,
  listSkills,
  loadPolicy,
  writeJson,
} from "./lib.mjs";

const policy = loadPolicy();
const { skills, overrides } = listSkills();
const hot = new Set(policy.hot ?? []);
const duplicates = policy.duplicates ?? {};
const candidates = policy.candidates ?? [];

const entries = skills.map((skill) => {
  const override = overrides.find((entry) => entry.id === skill.id);
  return {
    id: skill.id,
    source: skill.source,
    hot: hot.has(skill.id),
    description: skill.description,
    keywords: keywords(skill),
    lines: skill.lines,
    overridden: override ? override.shadowed : null,
  };
});

const hotEntries = entries.filter((entry) => entry.hot);
const coldEntries = entries.filter((entry) => !entry.hot);
const unclassified = entries
  .filter((entry) => !entry.hot && !(entry.id in duplicates))
  .map((entry) => entry.id);
const stalePolicy = [...hot, ...Object.keys(duplicates)].filter(
  (id) => !skills.some((skill) => skill.id === id)
);
const advertised = entries.reduce((sum, entry) => sum + entry.description.length, 0);

writeJson(MANIFEST_PATH, {
  generatedAt: new Date().toISOString(),
  policyVersion: policy.version,
  project: policy.owner,
  total: entries.length,
  hot: hotEntries.length,
  cold: coldEntries.length,
  inject: policy.inject,
  skills: entries,
});

fs.mkdirSync(ROUTING_DOC.replace(/[\\/][^\\/]+$/, ""), { recursive: true });
fs.writeFileSync(
  ROUTING_DOC,
  render(entries, { unclassified, stalePolicy, advertised, candidates }),
  "utf8"
);

console.log(
  `manifest: ${entries.length} skills (${hotEntries.length} hot, ${coldEntries.length} cold)`
);
console.log(
  `advertised descriptions: ${advertised} chars (~${estimateTokens("x".repeat(advertised))} tokens)`
);
if (unclassified.length) console.log(`outside the hot/priority set: ${unclassified.length}`);
if (stalePolicy.length)
  console.log(`policy entries with no installed skill: ${stalePolicy.join(", ")}`);

/** Eight distinctive tokens for docs and quick search. */
function keywords(skill) {
  const fromId = skill.id.split("-").filter((word) => word.length > 2);
  const seen = new Set(fromId);
  for (const word of skill.description
    .toLowerCase()
    .replace(/[^a-z0-9+#]+/g, " ")
    .split(" ")) {
    if (word.length > 3 && !seen.has(word) && seen.size < 8) seen.add(word);
  }
  return [...seen].slice(0, 8);
}

function render(list, meta) {
  const groups = policy.groups ?? {};
  const lines = [];

  lines.push("# Skill routing", "");
  lines.push(
    "How this project decides which of the machine-global agent skills to load. Generated by",
    "`pnpm skills:inventory` from `skills.policy.json` and the installed library — edit the policy,",
    "not this file.",
    ""
  );

  lines.push("## How it works", "");
  lines.push(
    "1. **Every installed skill is advertised** to the model on each step. This environment cannot",
    "   load a skill that has been hidden from that list (`metadata.opencode/autoinvoke: false`",
    "   makes a skill unloadable here), so nothing is hidden — see the warning under Maintenance.",
    "2. The **hot** set below is the curated priority for this project: the skills worth reaching",
    "   for first. It biases the matcher; it is not a visibility switch.",
    "3. Before a non-trivial task, `node scripts/skills/match.mjs` scores the prompt against every",
    "   skill description (plus hand-curated triggers) and the agent loads the best matches.",
    "4. Manual entry points: `/skills <task>` (match and load) and `/skills-audit` (integrity and",
    "   curation report).",
    ""
  );

  lines.push(
    `Totals: **${list.length}** installed · **${list.filter((e) => e.hot).length}** hot (priority) · ` +
      `**${list.filter((e) => !e.hot).length}** other · all advertised · ~${estimateTokens("x".repeat(meta.advertised))} tokens/step.`,
    ""
  );

  lines.push("## Hot skills", "");
  for (const [group, ids] of Object.entries(groups)) {
    const members = [];
    for (const pattern of ids) {
      if (pattern.endsWith("-*")) {
        const prefix = pattern.slice(0, -1);
        members.push(
          ...list
            .filter((entry) => entry.hot && entry.id.startsWith(prefix))
            .map((entry) => entry.id)
        );
      } else {
        members.push(
          ...list.filter((entry) => entry.hot && entry.id === pattern).map((entry) => entry.id)
        );
      }
    }
    const unique = [...new Set(members)].sort();
    if (!unique.length) continue;
    lines.push(
      `**${group}** (${unique.length}): ${unique.map((id) => `\`${id}\``).join(", ")}`,
      ""
    );
  }

  lines.push("## Skills outside the priority set", "");
  const families = new Map();
  for (const entry of list.filter((item) => !item.hot)) {
    const family = entry.id.split("-")[0];
    if (!families.has(family)) families.set(family, []);
    families.get(family).push(entry.id);
  }
  lines.push("| Family | Count | Skill IDs |", "| --- | --- | --- |");
  for (const [family, ids] of [...families.entries()].sort((a, b) => b[1].length - a[1].length)) {
    ids.sort();
    const shown = ids.length > 12 ? `${ids.slice(0, 12).join(", ")}, …` : ids.join(", ");
    lines.push(`| \`${family}\` | ${ids.length} | ${shown} |`);
  }
  lines.push("");

  if (meta.candidates.length) {
    lines.push("## Candidate additions", "");
    for (const candidate of meta.candidates) {
      lines.push(`- \`${candidate.id}\` (${candidate.source}) — ${candidate.why}`);
    }
    lines.push("");
  }

  if (meta.stalePolicy.length) {
    lines.push("## Policy entries with no installed skill", "");
    lines.push(meta.stalePolicy.map((id) => `\`${id}\``).join(", "), "");
  }

  lines.push("## Maintenance", "");
  lines.push(
    "- `pnpm skills:inventory` — regenerate this doc and the manifest.",
    "- `pnpm skills:audit` — duplicate, integrity, and curation report.",
    '- `pnpm skills:match "<task>"` — see what a prompt would route to.',
    "- `pnpm skills:policy` — dry-run report of the hot/cold split (informational only).",
    "",
    "> **Do not run `pnpm skills:policy:apply`.** This environment refuses to load a skill that is",
    "> hidden from the advertised list, so hiding a skill only makes it unusable. The hot/cold split",
    "> is a priority ranking and a matcher bias, not a visibility filter.",
    ""
  );

  return `${lines.join("\n")}\n`;
}
